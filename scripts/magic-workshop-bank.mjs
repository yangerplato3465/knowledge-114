import { shortestSolution, shortestPathAudit, applyAction } from '../src/games/magic-workshop/rules.ts';
import { readFileSync, writeFileSync } from 'node:fs';

// Offline enumeration: keep small classroom numbers; do not manufacture variants by scaling.
const gcd = (a, b) => b ? gcd(b, a % b) : a;
const rows = [];
for (const count of [2, 3]) {
  for (let a = 2; a <= 14; a++) for (let b = a + 1; b <= 14; b++) {
    for (const c of count === 2 ? [null] : Array.from({ length: 14 - b }, (_, i) => b + i + 1)) {
      const capacities = c === null ? [a, b] : [a, b, c];
      if (capacities.reduce(gcd) !== 1) continue;
      for (let target = 1; target < capacities.at(-1); target++) {
        if (capacities.includes(target)) continue;
        const rule = { capacities, target };
        const path = shortestSolution(rule);
        if (!path || path.length < 5 || path.length > 10) continue;
        if (count === 2 ? ![6, 8].includes(path.length) : path.length < 7) continue;
        if (count === 3 && capacities.some((_, i) => {
          const shorter = shortestSolution({ capacities: capacities.filter((_, j) => i !== j), target });
          return shorter && shorter.length <= path.length;
        })) continue;
        const audit = shortestPathAudit(rule);
        const families = new Set();
        const signatures = new Set();
        for (const solution of audit.paths) {
          signatures.add(solution.map(action => `${action.kind[0]}${action.from}${action.to ?? ''}`).join('.'));
          const received = new Set();
          const pours = new Set();
          let amounts = capacities.map(() => 0);
          for (const action of solution) {
            if (action.kind === 'empty') families.add('space');
            if (action.kind === 'pour') {
              if (received.has(action.from)) families.add('relay');
              received.add(action.to);
              const pair = `${action.from}-${action.to}`;
              if (pours.has(pair)) families.add('cycle');
              pours.add(pair);
            }
            amounts = applyAction(capacities, amounts, action);
          }
          if (amounts.findIndex(value => value === target) !== solution[0].from) families.add('switch');
        }
        if (audit.count > 1) families.add('compare');
        rows.push({ capacities, target, minimumSteps: path.length, families: [...families].sort(), signature: [...signatures].sort().join('|') });
      }
    }
  }
}
const structures = [...new Set(rows.map(row => row.signature))].sort();
const data = rows.map(({ capacities, target, minimumSteps, families, signature }) =>
  [capacities, target, minimumSteps, families, `route-${structures.indexOf(signature)}`]);
const output = '// Generated by node --experimental-strip-types scripts/magic-workshop-bank.mjs --write\n'
  + '// Capacities 2..14, primitive ratios, no redundant third bottle.\n'
  + 'export const BANK_ROWS: readonly (readonly [readonly number[], number, number, readonly string[], string])[] = '
  + '[\n' + data.map(row => '  ' + JSON.stringify(row)).join(',\n') + '\n];\n';
if (process.argv.includes('--write')) writeFileSync(new URL('../src/games/magic-workshop/generated-bank.ts', import.meta.url), output);
if (process.argv.includes('--check') && readFileSync(new URL('../src/games/magic-workshop/generated-bank.ts', import.meta.url), 'utf8').replaceAll('\r\n', '\n') !== output) throw new Error('魔法工坊題庫與產生器不一致');
for (const [tier, counts, families] of [[3, [2,2,2,2,2], ['cycle','space','cycle','space','cycle']], [4,[2,2,2,3,3],['cycle','space','cycle','relay','switch']], [5,[3,3,3,3,3],['cycle','compare','space','relay','switch']]]) {
  console.log(tier, counts.map((count,i) => {
    const pool = rows.filter(row => row.capacities.length === count && row.minimumSteps >= tier*2-1 && row.minimumSteps <= tier*2 && row.families.includes(families[i]));
    return { count: pool.length, structures: new Set(pool.map(row => row.signature)).size };
  }));
}
