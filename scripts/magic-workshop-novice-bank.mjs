import {readFileSync,writeFileSync} from 'node:fs';
import {shortestPathAudit} from '../src/games/magic-workshop/rules.ts';
const rows=[];
for(let a=2;a<=7;a++)for(let b=a+1;b<=12;b++)for(let target=1;target<b;target++){
  if(target===a)continue;
  const audit=shortestPathAudit({capacities:[a,b],target},100);
  if(audit?.steps!==4)continue;
  const family=audit.count>1?'compare':target===2*a?'accumulate':target===2*a-b?'remainder':'subtract';
  rows.push([[a,b],target,family,audit.count]);
}
const source='// Generated by scripts/magic-workshop-novice-bank.mjs --write; every goal is exactly four moves.\nexport const NOVICE_ROWS = '+JSON.stringify(rows,null,2)+' as const;\n';
const file=new URL('../src/games/magic-workshop/novice-bank.ts',import.meta.url);
if(process.argv.includes('--write'))writeFileSync(file,source);
else if(readFileSync(file,'utf8')!==source)throw new Error('見習生題庫需重新產生');
console.log(`${rows.length} 題四步題；${rows.filter(r=>r[3]>1).length} 題具有兩種最短解。`);
